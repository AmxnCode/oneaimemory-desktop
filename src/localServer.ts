import { createServer, type Server, type IncomingMessage, type ServerResponse } from 'node:http';
import { randomUUID, timingSafeEqual } from 'node:crypto';
import { redactEvent, type ConsciousnessEvent, type UserBlocklist } from '@oneconscious/shared';

/**
 * Localhost ingest endpoint for the browser extension.
 *
 * The extension cannot encrypt: it has no access to the passphrase, and putting
 * one in an extension would mean a second copy of the key in a far weaker
 * store. Instead it POSTs PLAINTEXT events here, and the desktop app — which
 * already holds the key — redacts, encrypts, queues, and syncs them.
 *
 * That keeps exactly one component able to decrypt, which is the whole premise
 * of the architecture.
 *
 * Hardening:
 *   - binds 127.0.0.1 only, so nothing off-machine can reach it
 *   - requires a bearer token generated by the app and pasted into the
 *     extension, so an arbitrary web page cannot POST fabricated activity
 *   - constant-time token comparison
 *   - CORS limited to chrome-extension:// and moz-extension:// origins
 *   - body size cap
 */

export const LOCAL_PORT = 41999;
const MAX_BODY_BYTES = 1_000_000;
const MAX_BATCH = 200;

export interface LocalServerDeps {
  getToken: () => string;
  getBlocklist: () => UserBlocklist;
  /** Category toggles, so the extension respects the same switches. */
  isTypeEnabled: (type: string) => boolean;
  isPaused: () => boolean;
  onEvent: (event: ConsciousnessEvent) => void;
  onBlocked: (type: string, reason: string) => void;
  deviceId: () => string;
}

function tokensMatch(provided: string, expected: string): boolean {
  const a = Buffer.from(provided);
  const b = Buffer.from(expected);
  if (a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}

function readBody(req: IncomingMessage): Promise<string> {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks: Buffer[] = [];
    req.on('data', (c: Buffer) => {
      size += c.length;
      if (size > MAX_BODY_BYTES) {
        reject(new Error('body_too_large'));
        req.destroy();
        return;
      }
      chunks.push(c);
    });
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    req.on('error', reject);
  });
}

const ALLOWED_ORIGIN = /^(chrome-extension|moz-extension|safari-web-extension):\/\//;

export function startLocalServer(deps: LocalServerDeps): Server {
  const server = createServer((req: IncomingMessage, res: ServerResponse) => {
    const origin = req.headers.origin ?? '';
    if (origin && ALLOWED_ORIGIN.test(origin)) {
      res.setHeader('Access-Control-Allow-Origin', origin);
      res.setHeader('Access-Control-Allow-Headers', 'content-type, authorization');
      res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
    }

    if (req.method === 'OPTIONS') {
      res.writeHead(204).end();
      return;
    }

    const json = (status: number, body: unknown) => {
      res.writeHead(status, { 'content-type': 'application/json' });
      res.end(JSON.stringify(body));
    };

    // Unauthenticated liveness probe so the extension can show connection
    // status without holding a valid token. Deliberately reveals nothing.
    if (req.method === 'GET' && req.url === '/ping') {
      json(200, { ok: true, app: 'oneconscious-desktop' });
      return;
    }

    if (req.method !== 'POST' || req.url !== '/collect') {
      json(404, { error: 'not_found' });
      return;
    }

    const auth = req.headers.authorization ?? '';
    const token = auth.startsWith('Bearer ') ? auth.slice(7).trim() : '';
    if (!token || !tokensMatch(token, deps.getToken())) {
      json(401, { error: 'invalid_token' });
      return;
    }

    if (deps.isPaused()) {
      // Accept-and-discard: the extension shouldn't spin retrying while paused.
      json(200, { accepted: 0, paused: true });
      return;
    }

    void readBody(req)
      .then((raw) => {
        let parsed: { events?: unknown };
        try {
          parsed = JSON.parse(raw) as { events?: unknown };
        } catch {
          json(400, { error: 'invalid_json' });
          return;
        }

        const batch = Array.isArray(parsed.events) ? parsed.events.slice(0, MAX_BATCH) : [];
        let accepted = 0;
        let blocked = 0;

        for (const item of batch) {
          const ev = item as { type?: string; payload?: Record<string, unknown>; timestamp?: string };
          if (!ev?.type || typeof ev.payload !== 'object' || ev.payload === null) continue;
          if (!deps.isTypeEnabled(ev.type)) continue;

          // Same filter the native collectors use — the extension is not
          // trusted to have redacted anything.
          const result = redactEvent({ type: ev.type, payload: ev.payload }, deps.getBlocklist());
          if (result.decision.action === 'drop') {
            blocked++;
            deps.onBlocked(ev.type, result.decision.reasons[0] ?? 'blocked');
            continue;
          }

          deps.onEvent({
            eventUuid: randomUUID(),
            deviceId: deps.deviceId(),
            // Trust the extension's timestamp only if it is sane; otherwise now.
            timestamp: isSaneTimestamp(ev.timestamp) ? ev.timestamp! : new Date().toISOString(),
            type: ev.type,
            payload: result.event!.payload,
          } as ConsciousnessEvent);
          accepted++;
        }

        json(200, { accepted, blocked });
      })
      .catch((err: Error) => {
        json(err.message === 'body_too_large' ? 413 : 500, { error: err.message });
      });
  });

  server.listen(LOCAL_PORT, '127.0.0.1');
  return server;
}

/** Reject timestamps far in the future or absurdly old. */
function isSaneTimestamp(ts: string | undefined): boolean {
  if (!ts) return false;
  const t = Date.parse(ts);
  if (Number.isNaN(t)) return false;
  const now = Date.now();
  return t <= now + 60_000 && t > now - 30 * 86400_000;
}
